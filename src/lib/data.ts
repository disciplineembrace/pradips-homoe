// ============================================================
// Search index — only over short fields, NOT the full text.
// Original code built a 15MB string array which killed performance.
// ============================================================
export type SearchEntry = {
  type: 'remedy' | 'rubric';
  id: string;
  name: string;
  author: string;
  text: string; // short fields only
};

let _searchIndex: SearchEntry[] | null = null;
export async function getSearchIndex(): Promise<SearchEntry[]> {
  if (_searchIndex) return _searchIndex;
  const [remedies, rubrics] = await Promise.all([getRemediesIndex(), getRubrics()]);
  _searchIndex = [];
  for (const r of remedies) {
    _searchIndex.push({
      type: 'remedy',
      id: r.id,
      name: r.name,
      author: r.author || '',
      // Use only short fields — no `full` text (was 4KB avg per remedy)
      text: (r.name + ' ' + (r.common || '') + ' ' + (r.keynote || '')).toLowerCase(),
    });
  }
  for (const r of rubrics) {
    _searchIndex.push({
      type: 'rubric',
      id: r.id,
      name: r.title,
      author: r.author || '',
      text: (r.title + ' ' + (r.path || '')).toLowerCase(),
    });
  }
  return _searchIndex;
}
